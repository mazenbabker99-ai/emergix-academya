## Question 1 of 15

A 45-year-old male was found unconscious at home and was brought into the Emergency Department by paramedics. On initial assessment at triage, his capillary blood glucose (BM) was 1.5 mmol/L. According to hypoglycemia management guidelines, what initial treatment should be given in this unconscious patient without intravenous access?

- **A.** 5% dextrose orally
- **B.** Wait for IV-line access and give IV 10% dextrose
- **C.** 70 to 80 ml of 50% glucose orally
- **D.** IM Pabrinex
- **E.** 1mg IM glucagon

**Correct Answer:** E
**Explanation:**
1mg IM glucagon is the recommended initial emergency treatment for severe hypoglycemia in an unconscious patient when intravenous (IV) access is not immediately available. Oral glucose/dextrose is strictly contraindicated in unconscious or drowsy patients due to high risk of airway compromise and aspiration. Once IV access is secured, 10% or 20% IV glucose should be administered.

## Question 2 of 15

A 25-year-old male presents to the Emergency Department with complaints of high fever, photophobia, and severe neck stiffness. You suspect acute bacterial meningitis. Which of the following is the characteristic microbiological feature of Neisseria meningitidis?

- **A.** Gram-positive coccobacilli
- **B.** Gram-negative diplococci
- **C.** Gram-positive rods
- **D.** Gram-negative rods
- **E.** Gram-positive diplococci

**Correct Answer:** B
**Explanation:**
Neisseria meningitidis (meningococcus) is a Gram-negative encapsulated diplococcus that causes meningococcal meningitis and meningococcal septicemia (meningococcemia). It is a major cause of bacterial meningitis in children and young adults.

## Question 3 of 15

A 45-year-old patient presents to the Emergency Department with complaints of vertical diplopia, especially noticeable when looking downwards (such as reading or walking downstairs). The patient reports that symptoms improve when tilting the head to the right. Physical examination reveals weakness in downward gaze of the left eye. Which cranial nerve is most likely affected in this patient?

- **A.** Oculomotor nerve (CN III)
- **B.** Trochlear nerve (CN IV)
- **C.** Optic nerve (CN II)
- **D.** Abducens nerve (CN VI)
- **E.** Trigeminal nerve (CN V)

**Correct Answer:** B
**Explanation:**
The trochlear nerve (CN IV) innervates the superior oblique muscle, which produces intorsion, depression, and abduction of the eyeball. Damage to the left CN IV results in weakness of downward gaze (especially in adduction), causing vertical diplopia. Patients classically compensate by tilting their head to the opposite (unaffected) side (here, to the right) to align the visual axes.

**High Yield Pearl:** The trochlear nerve is the smallest cranial nerve by number of axons, has the longest intracranial course, and is the only cranial nerve that exits from the posterior (dorsal) aspect of the brainstem.

## Question 4 of 15

A 25-year-old male patient with a history of blunt abdominal trauma presents to the Emergency Department with severe epigastric pain radiating directly through to the back. Serum lipase is markedly elevated. Which of the following represents the segmental sympathetic innervation of the pancreas?

- **A.** T4–T8
- **B.** T4–T10
- **C.** L2–L4
- **D.** L1–L2
- **E.** T6–T10

**Correct Answer:** E
**Explanation:**
The pancreas receives sympathetic pain afferents and innervation through the celiac plexus and greater/lesser splanchnic nerves derived from spinal segments T6 to T10.

**High Yield Visceral Segmental Levels:**
- Pancreas: T6–T10
- Gallbladder: T7–T9 and Phrenic nerve (C3–C5)
- Ascending & Transverse Colon: T10–T11
- Descending & Sigmoid Colon: L1–L2
- Kidney & Ureter: T10–L1
- Bladder: S2–S4 (parasympathetic) and T11–L2 (sympathetic)
- Appendix: T10 (referred to periumbilical region)

## Question 5 of 15

A 43-year-old male undergoes surgery to the posterior triangle of the neck, following which he notices numbness and loss of sensation around the clavicular and supraclavicular fossa region. Which of the following dermatomes is best localized to the supraclavicular region?

- **A.** T2
- **B.** C4
- **C.** C5
- **D.** C3
- **E.** C2

**Correct Answer:** D
**Explanation:**
In the Royal College of Emergency Medicine (RCEM) landmark system, C3 supplies the supraclavicular fossa at the mid-clavicular line, while C4 supplies the acromioclavicular joint / superior shoulder tip.

**Upper Limb Dermatome Landmarks:**
- C2: Occipital protuberance
- C3: Supraclavicular fossa at mid-clavicular line
- C4: Acromioclavicular joint
- C5: Lateral antecubital fossa
- C6: Dorsal surface of thumb proximal phalanx
- C7: Middle finger
- C8: Little finger (hypothenar eminence)
- T1: Medial antecubital fossa
- T2: Apex of axilla

## Question 6 of 15

A 32-year-old lady presents to the Emergency Department with severe pain and tenderness in the posterior ankle over the Achilles tendon. She recently completed a course of oral antibiotics prescribed by her GP for a complicated urinary tract infection. Which antibiotic class is classically associated with tendinopathy and tendon rupture?

- **A.** Macrolides
- **B.** Aminoglycosides
- **C.** Cephalosporins
- **D.** Quinolones (Fluoroquinolones)
- **E.** Tetracyclines

**Correct Answer:** D
**Explanation:**
Fluoroquinolones (such as ciprofloxacin, levofloxacin, and moxifloxacin) carry a prominent risk of tendinopathy and tendon rupture, most commonly affecting the Achilles tendon. Symptoms can occur during or up to several months after treatment. Quinolones are also known to cause QT prolongation predisposing to Torsades de pointes.

## Question 7 of 15

Which of the following dietary sources contains the highest calcium content among plant and non-dairy foods according to nutritional emergency medicine standards?

- **A.** Broccoli
- **B.** Sunflower seeds
- **C.** Tomato
- **D.** Soybeans (Soy products)
- **E.** Spinach

**Correct Answer:** D
**Explanation:**
Soybeans and fortified soy products (such as tofu) are exceptionally rich non-dairy sources of bioavailable dietary calcium (yielding 100–250 mg per serving). In the RCEM question bank, soybeans are recognized as the primary high-yield non-dairy source of calcium. Dairy products (especially hard cheese and yogurt) remain the highest overall calcium sources.

## Question 8 of 15

A 23-year-old pregnant woman in her second trimester, recently arriving from rural southern Vietnam, presents to the Emergency Department with high fevers, rigors, and chills. Peripheral blood film confirms Plasmodium falciparum malaria. Which of the following is the antimalarial treatment of choice for this patient?

- **A.** Primaquine
- **B.** Chloroquine
- **C.** Doxycycline
- **D.** Quinine
- **E.** Clindamycin monotherapy

**Correct Answer:** D
**Explanation:**
Oral or intravenous Quinine (combined with oral Clindamycin) is the safe and established treatment of choice for malaria in pregnancy, particularly in areas with chloroquine-resistant P. falciparum such as southern Vietnam and Southeast Asia. Primaquine and Doxycycline are strictly contraindicated in pregnancy due to fetal toxicity (teratogenicity, bone/tooth staining).

## Question 9 of 15

A 45-year-old male sustained a lacerated wound over his right knee two days ago and now presents with severe knee pain, fever, joint effusion, and inability to bear weight. Arthrocentesis reveals purulent synovial fluid with a white cell count of 85,000/mm³. Gram staining reveals Gram-positive cocci in clusters. What is the single most likely causative organism?

- **A.** Staphylococcus epidermidis
- **B.** Streptococcus pyogenes
- **C.** Staphylococcus aureus
- **D.** Escherichia coli
- **E.** Streptococcus pneumoniae

**Correct Answer:** C
**Explanation:**
Staphylococcus aureus is a Gram-positive coccus that characteristically grows in clusters ("grapes-like clusters") and is catalase-positive and coagulase-positive. It is the most common cause of acute bacterial septic arthritis in adults, especially after direct penetrating trauma or skin lacerations.

## Question 10 of 15

A 25-year-old male is brought to the Emergency Department with fever, headache, photophobia, neck stiffness, and a rapidly spreading non-blanching petechial and purpuric skin rash. What is the most likely causative organism?

- **A.** Escherichia coli
- **B.** Haemophilus influenzae
- **C.** Neisseria meningitidis
- **D.** Streptococcus pyogenes
- **E.** Streptococcus pneumoniae

**Correct Answer:** C
**Explanation:**
The classic triad of meningism (headache, fever, neck stiffness) accompanied by a petechial or purpuric non-blanching rash is the hallmark of meningococcal infection caused by Neisseria meningitidis (meningococcal meningitis / meningococcemia). This presentation warrants immediate empiric intravenous ceftriaxone.

## Question 11 of 15

A 45-year-old male presents with acute swelling, severe pain, warmth, and erythema of his right knee. Synovial fluid aspiration confirms acute bacterial septic arthritis. Which of the following pathogens is the single most common overall cause of native joint septic arthritis in adults?

- **A.** Staphylococcus aureus
- **B.** Streptococcus agalactiae
- **C.** Escherichia coli
- **D.** Staphylococcus epidermidis
- **E.** Streptococcus pyogenes

**Correct Answer:** A
**Explanation:**
Staphylococcus aureus accounts for over 50–60% of all cases of acute bacterial native joint septic arthritis in adults. In sexually active young adults presenting with migratory polyarthralgia and tenosynovitis, disseminated Neisseria gonorrhoeae must also be considered.

## Question 12 of 15

A 32-year-old male sustains a deep puncture wound to the plantar surface of his foot after stepping on a nail that pierced directly through his rubber-soled running shoe. According to microbiological classification, which of the following pathogens is categorized as a "conditional" pathogen that can cause acute deep wound infection under these specific conditions?

- **A.** Pseudomonas aeruginosa
- **B.** Neisseria gonorrhoeae
- **C.** Treponema pallidum
- **D.** Staphylococcus aureus
- **E.** Escherichia coli

**Correct Answer:** D
**Explanation:**
In microbiological pathogen classification:
- Conditional pathogens: Cause disease when specific host or local tissue conditions are altered (e.g., normal skin flora such as Staphylococcus aureus entering via deep puncture wounds or tissue necrosis).
- Opportunistic pathogens: Cause infection in immunocompromised hosts (e.g., Candida albicans, Pneumocystis jirovecii, Pseudomonas aeruginosa).
- Obligate pathogens: Always associated with disease and cannot survive as normal commensals (e.g., Mycobacterium tuberculosis, Treponema pallidum, Neisseria gonorrhoeae).
In RCEM classification, Staphylococcus aureus is the classic conditional pathogen example.

## Question 13 of 15

A 25-year-old male presents to the Emergency Department after being struck under the chin during a basketball game. He reports severe preauricular pain and presents with his jaw locked in a closed position. Physical examination reveals posterior displacement of the mandibular condyle. Which ligament is primarily responsible for preventing posterior and inferior dislocation of the temporomandibular joint (TMJ)?

- **A.** Stylomandibular ligament
- **B.** Sphenomandibular ligament
- **C.** Lateral pterygoid muscle tendon
- **D.** Temporomandibular (Lateral) ligament
- **E.** Sternoclavicular ligament

**Correct Answer:** D
**Explanation:**
The lateral temporomandibular ligament (lateral ligament) is the strongest ligament reinforcing the TMJ capsule. It specifically prevents excessive posterior and inferior displacement of the mandibular condyle. In traumatic posterior TMJ dislocation (where the jaw is locked in a closed position, unlike anterior dislocation where the mouth is locked open), this lateral temporomandibular ligament is compromised or torn.

## Question 14 of 15

During a clinical teaching session on cardiac anatomy in the Emergency Department, an emergency physician discusses acute coronary syndromes. Which of the following specialized conduction structures is most vulnerable to ischemia in acute occlusion of the Right Coronary Artery (RCA)?

- **A.** Left bundle branch
- **B.** Purkinje fibers of left ventricle
- **C.** Sinoatrial (SA) node
- **D.** Anterior two-thirds of interventricular septum
- **E.** Left circumflex branch

**Correct Answer:** C
**Explanation:**
The Right Coronary Artery (RCA) gives off the SA nodal artery in approximately 60% of people (and the left circumflex in 40%). The RCA also supplies the AV node via the AV nodal branch in approximately 90% of individuals (right dominant circulation). Therefore, acute proximal occlusion of the RCA (inferior STEMI) frequently leads to sinus node dysfunction, sinus bradycardia, sinus pause, or AV nodal heart block.

**Key Correlative Anatomy:**
- LAD: Supplies anterior 2/3 of interventricular septum, anterior wall, and bundle branches.
- LCX: Supplies lateral left ventricular free wall.
- RCA: Supplies right ventricle, SA node (60%), AV node (90%), and posterior 1/3 of septum (via PDA).

